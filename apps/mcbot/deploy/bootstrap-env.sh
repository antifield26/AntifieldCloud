  case "$arg" in
    --rotate-token) ROTATE_TOKEN=1 ;;
    --rotate-control-token) ROTATE_CONTROL_TOKEN=1 ;;
    *) echo "unknown argument: $arg" >&2; exit 2 ;;
  esac
done

